-- Infraestrutura aditiva do Log DK. Não copia cadastros e não grava evento.
create table if not exists public.dk_events (
  seq bigint generated by default as identity primary key,
  operation_id uuid not null unique,
  event_type text not null,
  entity_type text not null,
  entity_id text null,
  action text null,
  record_version bigint null,
  module text null,
  empresa_id text null,
  filial_id text null,
  actor_user_id text null,
  actor_session_id uuid null,
  payload jsonb not null default '{}'::jsonb,
  visibility text null,
  created_at timestamptz not null default now(),
  constraint dk_events_payload_object check (jsonb_typeof(payload) = 'object')
);

alter table public.dk_events enable row level security;
revoke all on table public.dk_events from public, anon, authenticated, service_role;
grant select on table public.dk_events to service_role;

do $$
declare
  seq_nome text;
begin
  seq_nome := pg_get_serial_sequence('public.dk_events', 'seq');
  if seq_nome is not null then
    execute format('revoke all on sequence %s from public, anon, authenticated', seq_nome);
  end if;
end $$;

notify pgrst, 'reload schema';
