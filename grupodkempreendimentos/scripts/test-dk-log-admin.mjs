import assert from "node:assert/strict";
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const raiz = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const acesso = require("../lib/dk-log-acesso.cjs");

const html = fs.readFileSync(path.join(raiz, "index.html"), "utf8");
const ui = execSync("git show HEAD:grupodkempreendimentos/portal-locadora-ui.js", {
  cwd: path.resolve(raiz, ".."),
  encoding: "utf8",
  maxBuffer: 8 * 1024 * 1024,
}).replace(/\r\n/g, "\n");
const api = fs.readFileSync(path.join(raiz, "api", "dk-log.js"), "utf8");
const doc = html.indexOf('id="btn-locadora-documentos"');
const log = html.indexOf('id="btn-locadora-log"');
const fin = html.indexOf('id="btn-locadora-financeiro"');
assert.ok(doc >= 0 && log > doc && fin > log);
assert.ok(html.includes(">Log</button>"));
assert.ok(html.includes('id="panel-log-locadora"'));
assert.ok(html.includes("Log DK — eventos duráveis registrados no servidor"));
assert.ok(!html.includes("nesta etapa não é consultada"));
assert.ok(html.includes("portal-log-ui.js?v=20261029logdk10"));
assert.ok(html.includes('id="portal-log-usuarios"'));
assert.ok(html.includes('id="portal-log-detalhe"'));
assert.ok(html.includes('id="portal-log-lista"'));
assert.ok(html.includes('id="btn-voltar-log-locadora"'));
assert.ok(!html.includes("dk_events_fake"));

assert.ok(ui.includes('id="btn-locadora-log"') || ui.includes("btn-locadora-log"));
assert.ok(ui.includes("portalPodeAcessarLog"));
assert.ok(ui.includes('btnLog?.classList.toggle("hidden", !allowFin)'));
assert.ok(ui.includes('rest === "log"'));
assert.ok(ui.includes("function portalDelegarPagamento"));
assert.ok(!ui.includes("evento inventado"));

const authEm = api.indexOf("requireLiveSession");
const dadosEm = api.indexOf("estadoLog");
assert.ok(authEm >= 0 && dadosEm > authEm);
assert.ok(api.includes("lerEventosLog"));
assert.ok(api.includes("allowService: false"));
assert.ok(!api.includes("dk_pagamento"));
assert.ok(!api.includes("dk_locacao"));
assert.ok(!api.includes("DELETE"));
assert.ok(!api.includes("TRUNCATE"));

assert.deepStrictEqual(acesso.decidirAcessoLog({ ok: true, typ: "equipa", role: "owner" }), { ok: true });
assert.strictEqual(acesso.decidirAcessoLog({ ok: true, typ: "equipa", role: "operacao" }).status, 403);
assert.strictEqual(acesso.decidirAcessoLog({ ok: true, typ: "equipa", role: "operacao" }).reason, "log_somente_administrador");
assert.strictEqual(acesso.decidirAcessoLog({ ok: true, typ: "cliente", role: "owner" }).status, 403);
assert.strictEqual(acesso.decidirAcessoLog({ ok: true, typ: "equipa", role: "owner", service: true }).status, 403);
assert.strictEqual(acesso.decidirAcessoLog({ ok: false, status: 401, reason: "unauthorized" }).status, 401);
const estado = acesso.estadoLog();
assert.strictEqual(estado.estado, "Log DK — eventos duráveis registrados no servidor");
assert.strictEqual(estado.fonte, "dk_events");
assert.deepStrictEqual(estado.events, []);
assert.deepStrictEqual(estado.eventos, []);
assert.strictEqual(estado.quantidade, 0);
assert.strictEqual(estado.server_event_seq, 0);
assert.strictEqual(estado.fallback, false);
assert.deepStrictEqual(estado.colunas, ["audit_no", "horario", "usuario", "maquina", "resumo"]);
assert.deepStrictEqual(estado.sessoes, []);

const sql = fs.readFileSync(path.join(raiz, "supabase", "dk-events.sql"), "utf8").toLowerCase();
assert.ok(sql.includes("create table if not exists public.dk_events"));
assert.ok(sql.includes("generated by default as identity primary key"));
assert.ok(sql.includes("operation_id uuid not null unique"));
assert.ok(sql.includes("enable row level security"));
assert.ok(sql.includes("revoke all on table public.dk_events from public, anon, authenticated, service_role"));
assert.ok(sql.includes("grant select on table public.dk_events to service_role"));
assert.ok(!sql.includes("drop table"));
assert.ok(!sql.includes("truncate"));
assert.ok(!/\bdelete\b/.test(sql));

const leitura = require("../lib/dk-log-leitura.cjs");
const vazio = await leitura.lerEventosLog(async () => ({ ok: true, status: 200, data: [], contentRange: "*/0" }));
assert.strictEqual(vazio.ok, true);
assert.deepStrictEqual(vazio.events, []);
assert.strictEqual(vazio.quantidade, 0);
assert.strictEqual(vazio.server_event_seq, 0);
const um = await leitura.lerEventosLog(async () => ({
  ok: true,
  status: 200,
  contentRange: "0-0/1",
  data: [{ seq: 7, event_type: "teste", entity_type: "nenhum", payload: { ok: true }, created_at: "2026-10-28T00:00:00Z" }],
}));
assert.strictEqual(um.events[0].seq, 7);
assert.strictEqual(um.quantidade, 1);
assert.strictEqual(um.server_event_seq, 7);
assert.strictEqual(um.events[0].summary, "teste");
assert.strictEqual(Object.prototype.hasOwnProperty.call(um.events[0], "payload"), false);
const negado = await leitura.lerEventosLog(async () => ({ ok: false, status: 401, data: {} }));
assert.strictEqual(negado.ok, false);
assert.deepStrictEqual(negado.events, []);

